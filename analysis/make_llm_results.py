#!/usr/bin/env python3
"""Table, figure and LaTeX numbers of the LLM-controller results, computed only from result files.

Inputs : results/<corpus>/llm_controllers_dev_{rrf,cvx}.json (llm_controllers.py) and
         ../llm_mac/<corpus>-llm/manifest.json (LLM call statistics).
Outputs: <article>/generated/tab_llm.tex, <article>/generated/llm_numbers.tex, <article>/figures/Fig5.{pdf,eps}

    python make_llm_results.py <article_dir>
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

HERE = Path(__file__).resolve().parent
LLM = HERE.parent / "llm_mac"
CORPORA = [("Hemo", "hemophilia-dev", "Haemophilia (dev)"), ("SciFact", "scifact", "SciFact"),
           ("NFCorpus", "nfcorpus", "NFCorpus"), ("TrecCovid", "trec-covid", "TREC-COVID")]
CTRL = [("FIXED", "Fixed", r"Fixed $a^\ast$"), ("B1", "Bone", "B1 LLM, query"), ("B2", "Btwo", "B2 LLM, evidence"), ("DAT", "Dat", "DAT LLM, top-1"),
        ("A3", "Athree", "A3 signals"), ("A3+L", "AthreeL", "A3+L signals + LLM"),
        ("C(eps=0.02)", "Ctwo", r"C, $\varepsilon=0.02$"), ("C+L(eps=0.02)", "CLtwo", r"C+L, $\varepsilon=0.02$"),
        ("C+L(eps=0.05)", "CLfive", r"C+L, $\varepsilon=0.05$"), ("ORACLE", "Oracle", "Oracle")]
FAM = [("rrf", "Rrf", "Weighted RRF"), ("cvx", "Cvx", "Convex fusion")]

plt.rcParams.update({"font.family": "sans-serif", "font.sans-serif": ["Arial", "Helvetica", "DejaVu Sans"],
                     "font.size": 9, "axes.linewidth": 0.6, "lines.linewidth": 1.4, "pdf.fonttype": 42, "ps.fonttype": 42})


def load():
    R = {}
    for key, d, _ in CORPORA:
        for fam, _, _ in FAM:
            R[key, fam] = json.loads((HERE / "results" / d / f"llm_controllers_dev_{fam}.json").read_text())
    M = {key: json.loads((LLM / f"{d}-llm" / "manifest.json").read_text()) for key, d, _ in CORPORA}
    for key, d, _ in CORPORA:
        M[key]["dat"] = json.loads((LLM / f"{d}-dat" / "manifest.json").read_text())
    return R, M


def tex_table(R) -> str:
    cols = "l" + "rr" * len(CORPORA)
    head = " & ".join(rf"\multicolumn{{2}}{{c}}{{{lab}}}" for _, _, lab in CORPORA)
    rules = "".join(rf"\cmidrule{{{2 + 2 * i}-{3 + 2 * i}}}" for i in range(len(CORPORA)))
    sub = " & ".join([r"$\Delta$ & Loss\%"] * len(CORPORA))
    lines = [rf"\begin{{tabular*}}{{\textwidth}}{{@{{\extracolsep\fill}}{cols}}}", r"\toprule",
             f" & {head}\\\\", rules, f"Controller & {sub}\\\\"]
    for fam, _, flab in FAM:
        lines += [r"\midrule", rf"\multicolumn{{{1 + 2 * len(CORPORA)}}}{{l}}{{\emph{{{flab}}}}}\\"]
        for c, _, clab in CTRL:
            if c == "ORACLE":
                lines.append(r"\cmidrule{1-" + str(1 + 2 * len(CORPORA)) + "}")
            cells = []
            for key, _, _ in CORPORA:
                m = R[key, fam]["controllers"][c]
                cells += [f"{m['gain']['mean']:+.3f}", f"{100 * m['loss']['mean']:.1f}"]
            lines.append(f"{clab} & " + " & ".join(cells) + r"\\")
    lines += [r"\botrule", r"\end{tabular*}"]
    return "\n".join(lines) + "\n"


def tex_numbers(R, M) -> str:
    out = ["% generated by make_llm_results.py -- do not edit"]

    def nc(name, val):
        out.append(rf"\newcommand{{\{name}}}{{{val}}}")
    for key, _, _ in CORPORA:
        s = R[key, "rrf"]
        nc(f"llPool{key}", s["dev_pool"])
        nc(f"llCal{key}", s["split_sizes"][1])
        for fam, F, _ in FAM:
            cs = R[key, fam]["controllers"]
            for c, C, _ in CTRL:
                m = cs[c]
                nc(f"llGain{key}{C}{F}", f"{m['gain']['mean']:+.3f}")
                nc(f"llGainLo{key}{C}{F}", f"{m['gain']['p2.5']:+.3f}")
                nc(f"llGainHi{key}{C}{F}", f"{m['gain']['p97.5']:+.3f}")
                nc(f"llLoss{key}{C}{F}", f"{100 * m['loss']['mean']:.1f}")
                nc(f"llDev{key}{C}{F}", f"{100 * m['dev']['mean']:.1f}")
                nc(f"llMeanLoss{key}{C}{F}", f"{m['mean_loss']['mean']:.4f}")
            orc = cs["ORACLE"]["gain"]["mean"]
            for c, C in (("B1", "Bone"), ("B2", "Btwo"), ("DAT", "Dat")):
                nc(f"llRecover{key}{C}{F}", f"{100 * cs[c]['gain']['mean'] / orc:.0f}")
        m = M[key]
        nc(f"llQueries{key}", m["queries"])
        nc(f"llCalls{key}", m["total_calls"])
        nc(f"llInvalid{key}", m["invalid_b2_samples"])
        nc(f"llSecPerCall{key}", f"{m['total_llm_seconds'] / m['total_calls']:.1f}")
        nc(f"llDatInvalid{key}", m["dat"]["invalid"])
        nc(f"llDatCalls{key}", m["dat"]["total_calls"])
    dc = sum(M[k]["dat"]["total_calls"] for k, _, _ in CORPORA)
    nc("llDatCallsTotal", f"{dc:,}".replace(",", "{,}"))
    nc("llDatInvalidTotal", sum(M[k]["dat"]["invalid"] for k, _, _ in CORPORA))
    # median seconds per call (the mean includes calls interrupted by system sleep)
    import csv as _csv
    secs = [float(r["llm_seconds"]) for _, d, _ in CORPORA for r in _csv.DictReader(open(LLM / f"{d}-dat" / "dat_features.csv"))]
    nc("llDatSecPerCall", f"{np.median(secs):.1f}")
    tot_calls = sum(M[k]["total_calls"] for k, _, _ in CORPORA)
    tot_sec = sum(M[k]["total_llm_seconds"] for k, _, _ in CORPORA)
    nc("llCallsTotal", f"{tot_calls:,}".replace(",", "{,}"))
    nc("llInvalidTotal", sum(M[k]["invalid_b2_samples"] for k, _, _ in CORPORA))
    nc("llSecPerCallAll", f"{tot_sec / tot_calls:.1f}")
    # maximum measured mean loss of every C / C+L setting vs its epsilon (validity check, all corpora and families)
    worst = []
    for (key, fam), s in R.items():
        for c, m in s["controllers"].items():
            if c.startswith("C"):
                eps = float(c.split("=")[1].rstrip(")"))
                worst.append(m["mean_loss"]["mean"] / eps)
    nc("llWorstLossRatio", f"{max(worst):.2f}")
    return "\n".join(out) + "\n"


def fig_llm(R, out: Path):
    show = [("B1", "B1"), ("B2", "B2"), ("DAT", "DAT"), ("A3", "A3"), ("A3+L", "A3+L"), ("C+L(eps=0.02)", r"C+L, $\varepsilon$=0.02")]
    markers = ["o", "s", "^", "D"]
    fig, axes = plt.subplots(1, 2, figsize=(7.0, 3.2), sharey=True)
    y = np.arange(len(show))[::-1]
    off = np.linspace(-0.27, 0.27, len(CORPORA))
    for ax, (fam, _, flab) in zip(axes, FAM):
        for j, (key, _, lab) in enumerate(CORPORA):
            cs = R[key, fam]["controllers"]
            orc = cs["ORACLE"]["gain"]["mean"]
            g = np.array([cs[c]["gain"]["mean"] for c, _ in show])
            lo = g - np.array([cs[c]["gain"]["p2.5"] for c, _ in show])
            hi = np.array([cs[c]["gain"]["p97.5"] for c, _ in show]) - g
            ax.errorbar(g, y + off[j], xerr=[lo, hi], fmt=markers[j], color="black", mfc="black" if j % 2 == 0 else "white",
                        ms=4, elinewidth=0.6, capsize=1.5, label=lab)
            ax.plot([orc], [len(show) - 0.35 + off[j] * 0.3], markers[j], color="0.45", mfc="0.45" if j % 2 == 0 else "white", ms=3.5)
        ax.axvline(0, color="0.4", linewidth=0.8, linestyle=(0, (4, 2)))
        ax.set_title(flab, fontsize=9)
        ax.set_xlabel(r"Mean $\Delta$nDCG@10 vs. $a^\ast$")
        ax.spines[["top", "right"]].set_visible(False)
    axes[0].set_yticks(list(y) + [len(show) - 0.35], [l for _, l in show] + ["Oracle (grey)"])
    axes[0].text(-0.3, 1.04, "a", transform=axes[0].transAxes, fontweight="bold")
    axes[1].text(-0.05, 1.04, "b", transform=axes[1].transAxes, fontweight="bold")
    axes[0].legend(frameon=False, fontsize=7.5, loc="upper center", bbox_to_anchor=(1.05, -0.22), ncol=len(CORPORA))
    fig.tight_layout()
    for ext in ("pdf", "eps"):
        fig.savefig(out / f"Fig5.{ext}", bbox_inches="tight")
    plt.close(fig)


def main():
    art = Path(sys.argv[1])
    R, M = load()
    (art / "generated" / "tab_llm.tex").write_text(tex_table(R))
    (art / "generated" / "llm_numbers.tex").write_text(tex_numbers(R, M))
    fig_llm(R, art / "figures")
    print("written: generated/tab_llm.tex, generated/llm_numbers.tex, figures/Fig5.pdf/.eps")


if __name__ == "__main__":
    main()
