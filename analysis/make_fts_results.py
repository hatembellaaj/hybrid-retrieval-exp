#!/usr/bin/env python3
"""Table and LaTeX numbers of the FTS / A0 results, computed only from results/fts_dev.json (fts_analysis.py).

Outputs: <article>/generated/tab_fts.tex, <article>/generated/fts_numbers.tex

    python make_fts_results.py <article_dir>
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
LABEL = {"Hemo": r"Haemo.\ (dev)", "SciFact": "SciFact", "NFCorpus": "NFCorpus", "TrecCovid": "TREC-COVID", "FiQA": "FiQA"}
CTRL = [("A0", "Azero"), ("A3", "Athree"), ("C(eps=0.02)", "Ctwo"), ("C(eps=0.05)", "Cfive"), ("ORACLE", "Oracle")]


def g3(x: float) -> str:
    s = f"{x:+.3f}"
    return "0.000" if s in ("+0.000", "-0.000") else s


def ctrl(r, name):
    return r["A0"] if name == "A0" else r["controllers_fts"][name]


def table(R) -> str:
    lines = [r"\setlength{\tabcolsep}{3pt}",
             r"\begin{tabular*}{\textwidth}{@{\extracolsep\fill}lrrcrrrrrrr}", r"\toprule",
             r" & & FTS & \multicolumn{3}{c}{Fixed RRF, FTS} & \multicolumn{4}{c}{$\Delta$ vs.\ $a^\ast_{\mathrm{FTS}}$ (Loss\%)} & BM25\\",
             r"\cmidrule{4-6}\cmidrule{7-10}",
             r"Set & Strict & alone & $w^\ast_{\mathrm{lex}}$ & nDCG & Oracle & A0 & A3 & C$_{0.02}$ & Oracle & $-$FTS\\",
             r"\midrule"]
    for k, r in R.items():
        hf, hb = r["headroom_fts"], r["headroom_bm25"]
        cells = [LABEL[k], f"{r['strict_match_share_all'] * 100:.0f}\\%", f"{hf['lex']:.3f}",
                 f"{hf['best_w']:g}", f"{hf['fixed']:.3f}", f"+{hf['rel']:.1f}\\%"]
        for name in ("A0", "A3", "C(eps=0.02)"):
            m = ctrl(r, name)
            cells.append(f"{g3(m['gain']['mean'])} ({100 * m['loss']['mean']:.0f})")
        cells.append(f"{ctrl(r, 'ORACLE')['gain']['mean']:+.3f}")
        cells.append(f"{r['bm25_vs_fts_fixed']['diff']['mean']:+.3f}")
        lines.append(" & ".join(cells) + r"\\")
    lines += [r"\botrule", r"\end{tabular*}"]
    return "\n".join(lines) + "\n"


def numbers(R) -> str:
    out = ["% generated by make_fts_results.py -- do not edit"]

    def nc(n, v):
        out.append(rf"\newcommand{{\{n}}}{{{v}}}")
    worst = []
    for k, r in R.items():
        hf, hb = r["headroom_fts"], r["headroom_bm25"]
        nc(f"ftsStrict{k}", f"{100 * r['strict_match_share_all']:.0f}")
        nc(f"ftsLex{k}", f"{hf['lex']:.3f}")
        nc(f"ftsLexBM{k}", f"{hb['lex']:.3f}")
        nc(f"ftsDense{k}", f"{hf['dense']:.3f}")
        nc(f"ftsBestW{k}", f"{hf['best_w']:g}")
        nc(f"ftsBestWBM{k}", f"{hb['best_w']:g}")
        nc(f"ftsRel{k}", f"{hf['rel']:.1f}")
        nc(f"ftsRelBM{k}", f"{hb['rel']:.1f}")
        nc(f"ftsPool{k}", r["dev_pool"])
        nc(f"ftsCal{k}", r["split_sizes"][1])
        nc(f"ftsBMminusFTS{k}", f"{r['bm25_vs_fts_fixed']['diff']['mean']:+.3f}")
        nc(f"ftsAzeroVsWone{k}", f"{r['A0']['gain_vs_w1']['mean']:+.3f}")
        for name, C in CTRL:
            m = ctrl(r, name)
            nc(f"ftsGain{k}{C}", g3(m['gain']['mean']))
            nc(f"ftsGainLo{k}{C}", f"{m['gain']['p2.5']:+.3f}")
            nc(f"ftsGainHi{k}{C}", f"{m['gain']['p97.5']:+.3f}")
            nc(f"ftsLoss{k}{C}", f"{100 * m['loss']['mean']:.0f}")
            nc(f"ftsMeanLoss{k}{C}", f"{m['mean_loss']['mean']:.4f}")
            if name.startswith("C("):
                worst.append(m["mean_loss"]["mean"] / float(name.split("=")[1].rstrip(")")))
    nc("ftsWorstLossRatio", f"{max(worst):.2f}")
    return "\n".join(out) + "\n"


def main():
    art = Path(sys.argv[1])
    R = json.loads((HERE / "results" / "fts_dev.json").read_text())
    (art / "generated" / "tab_fts.tex").write_text(table(R))
    (art / "generated" / "fts_numbers.tex").write_text(numbers(R))
    print("written: generated/tab_fts.tex, generated/fts_numbers.tex")


if __name__ == "__main__":
    main()
