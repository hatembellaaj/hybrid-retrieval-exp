#!/usr/bin/env python3
"""Tables, figure and LaTeX numbers of the locked test, computed only from results/locked_test/run/results.json.

Outputs: <article>/generated/tab_test_public.tex, tab_test_clin.tex, test_numbers.tex, <article>/figures/Fig7.{pdf,eps}

    python make_test_results.py <article_dir>
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

HERE = Path(__file__).resolve().parent
R = json.loads((HERE / "results" / "locked_test" / "run" / "results.json").read_text())
PUB = [("scifact", "SciFact", "SciFact"), ("nfcorpus", "NFCorpus", "NFCorpus"), ("trec-covid", "TrecCovid", "TREC-COVID"),
       ("fiqa", "FiQA", "FiQA")]
CONF = [("bm25|rrf", "BmRrf", "BM25, RRF"), ("bm25|cvx", "BmCvx", "BM25, convex"), ("fts|rrf", "FtsRrf", "FTS, RRF")]
VAR = [("a_raw", "Raw", "(a) raw"), ("b_mapped", "Mapped", "(b) mapped"), ("c_grade3", "Strict", "(c) grade 3")]
CTRL = [("A2", "Atwo", "A2"), ("A3", "Athree", "A3"), ("C(eps=0.02)", "Ctwo", r"C$_{0.02}$"), ("B1", "Bone", "B1"),
        ("B2", "Btwo", "B2"), ("DAT", "Dat", "DAT"), ("C+L(eps=0.02)", "CLtwo", r"C+L$_{0.02}$"), ("A0", "Azero", "A0"),
        ("ORACLE", "Oracle", "Oracle")]

plt.rcParams.update({"font.family": "sans-serif", "font.sans-serif": ["Arial", "Helvetica", "DejaVu Sans"],
                     "font.size": 9, "axes.linewidth": 0.6, "pdf.fonttype": 42, "ps.fonttype": 42})


def g3(x):
    s = f"{x:+.3f}"
    return "0.000" if s in ("+0.000", "-0.000") else s


def cell(C, name):
    if name not in C:
        return "--"
    m = C[name]
    star = r"$^\ast$" if m.get("p_holm", 1) < 0.05 else ""
    return g3(m["gain"]) + star


def tab_public():
    cols = [c for c in CTRL]
    lines = [r"\setlength{\tabcolsep}{3pt}",
             r"\begin{tabular*}{\textwidth}{@{\extracolsep\fill}llr" + "r" * (len(cols) + 1) + "}", r"\toprule",
             "Corpus & Configuration & $n$ & Fixed & " + " & ".join(l for _, _, l in cols) + r"\\", r"\midrule"]
    for i, (c, _, lab) in enumerate(PUB):
        if i:
            lines.append(r"\midrule")
        for j, (k, _, klab) in enumerate(CONF):
            r = R["public"][f"{c}|{k}"]
            C = r["controllers"]
            lines.append((lab if j == 0 else "") + f" & {klab} & {r['n_test'] if j == 0 else ''} & "
                         f"{C['FIXED']['ndcg10']:.3f} & " + " & ".join(cell(C, n) for n, _, _ in cols) + r"\\")
    lines += [r"\botrule", r"\end{tabular*}"]
    return "\n".join(lines) + "\n"


def tab_clin():
    cols = [c for c in CTRL]
    lines = [r"\setlength{\tabcolsep}{3pt}",
             r"\begin{tabular*}{\textwidth}{@{\extracolsep\fill}llr" + "r" * (len(cols) + 2) + "}", r"\toprule",
             "Configuration & Relevance & $n$ & Fixed & In-s. & " + " & ".join(l for _, _, l in cols) + r"\\",
             r"\midrule"]
    for i, (k, _, klab) in enumerate(CONF):
        if i:
            lines.append(r"\midrule")
        for j, (v, _, vlab) in enumerate(VAR):
            r = R["clinical"][f"hemophilia-clin|{k}|{v}"]
            C = r["primary"]
            lines.append((klab if j == 0 else "") + f" & {vlab} & {r['n_questions_with_relevant']} & "
                         f"{C['FIXED']['ndcg10']:.3f} & {g3(C['FIXED_INSAMPLE']['gain'])} & "
                         + " & ".join(cell(C, n) for n, _, _ in cols) + r"\\")
    lines += [r"\botrule", r"\end{tabular*}"]
    return "\n".join(lines) + "\n"


def numbers():
    out = ["% generated by make_test_results.py -- do not edit"]

    def nc(n, v):
        out.append(rf"\newcommand{{\{n}}}{{{v}}}")

    def put(prefix, C):
        for n, N, _ in CTRL + [("FIXED", "Fixed", ""), ("C(eps=0.05)", "Cfive", ""), ("C+L(eps=0.05)", "CLfive", ""),
                                ("FIXED_INSAMPLE", "Insample", "")]:
            if n in C:
                m = C[n]
                nc(f"{prefix}Gain{N}", g3(m["gain"]))
                nc(f"{prefix}GainLo{N}", g3(m["gain_ci95"][0]))
                nc(f"{prefix}GainHi{N}", g3(m["gain_ci95"][1]))
                nc(f"{prefix}Loss{N}", f"{100 * m['loss']:.0f}")
                nc(f"{prefix}MeanLoss{N}", f"{m['mean_loss']:.4f}")
                nc(f"{prefix}Ndcg{N}", f"{m['ndcg10']:.3f}")
                if "p_holm" in m:
                    nc(f"{prefix}Pholm{N}", f"{m['p_holm']:.3f}")
    for c, C_, _ in PUB:
        nc(f"tsN{C_}", R["public"][f"{c}|bm25|rrf"]["n_test"])
        for k, K_, _ in CONF:
            put(f"ts{C_}{K_}", R["public"][f"{c}|{k}"]["controllers"])
    for k, K_, _ in CONF:
        for v, V_, _ in VAR:
            r = R["clinical"][f"hemophilia-clin|{k}|{v}"]
            put(f"tc{K_}{V_}", r["primary"])
            put(f"tcS{K_}{V_}", r["secondary_recalibrated"]["controllers"])
            nc(f"tcN{K_}{V_}", r["n_questions_with_relevant"])
        r = R["clinical"][f"hemophilia-clin|{k}|a_raw"]
        nc(f"tcAstarDev{K_}", r["a_star_dev"].split("_")[1][1:])
        nc(f"tcAstarIns{K_}", r["a_star_insample"].split("_")[1][1:])
    u = R["clinical"]["hemophilia-clin|fts|rrf|a_raw"]["unjudged_share_top10"]
    nc("tcUnjFtsLex", f"{100 * u['lex_only']:.0f}")
    nc("tcUnjFtsWone", f"{100 * u['rrf_w1.0']:.0f}")
    nc("tcUnjFtsA", f"{100 * u['A0_production']:.0f}")
    # risk check counts
    tot = exc = 0
    worst_pub = []
    for part, items in (("pub", [(k, r["controllers"]) for k, r in R["public"].items()]),
                        ("clin", [(k + s, (r["primary"] if s == "P" else r["secondary_recalibrated"]["controllers"]))
                                  for k, r in R["clinical"].items() if k != "mapping_b" for s in ("P", "S")])):
        t = e = 0
        for k, C in items:
            for n, m in C.items():
                if n.startswith("C"):
                    eps = float(n.split("=")[1].rstrip(")"))
                    t += 1
                    e += m["mean_loss"] > eps
                    if part == "pub":
                        worst_pub.append(m["mean_loss"] / eps)
        nc(f"tsRisk{'Pub' if part == 'pub' else 'Clin'}Settings", t)
        nc(f"tsRisk{'Pub' if part == 'pub' else 'Clin'}Exceed", e)
        tot, exc = tot + t, exc + e
    for lex, L in (("bm25", "Bm"), ("fts", "Fts")):
        t = e = 0
        for k, r in R["clinical"].items():
            if k == "mapping_b" or f"|{lex}|" not in k:
                continue
            for C in (r["primary"], r["secondary_recalibrated"]["controllers"]):
                for n, m in C.items():
                    if n.startswith("C"):
                        t += 1
                        e += m["mean_loss"] > float(n.split("=")[1].rstrip(")"))
        nc(f"tsRiskClin{L}Settings", t)
        nc(f"tsRiskClin{L}Exceed", e)
    nc("tsRiskSettings", tot)
    nc("tsRiskHeld", tot - exc)
    nc("tsRiskWorstPub", f"{max(worst_pub):.2f}")
    return "\n".join(out) + "\n"


def fig(out: Path):
    show = [("A2", "A2"), ("A3", "A3"), ("C(eps=0.02)", r"C, $\varepsilon$=0.02"), ("B1", "B1"), ("B2", "B2"), ("DAT", "DAT"),
            ("C+L(eps=0.02)", r"C+L, $\varepsilon$=0.02")]
    mk = ["o", "s", "^", "D"]
    fig, axes = plt.subplots(1, 2, figsize=(7.0, 3.2), sharey=True)
    y = np.arange(len(show))[::-1]
    sets = [[(R["public"][f"{c}|bm25|rrf"]["controllers"], lab) for c, _, lab in PUB],
            [(R["clinical"][f"hemophilia-clin|bm25|rrf|{v}"]["primary"], lab) for v, _, lab in VAR]]
    titles = ["a  Public corpora (locked test)", "b  Clinical questions (primary)"]
    for ax, S, t in zip(axes, sets, titles):
        off = np.linspace(-0.25, 0.25, len(S))
        for j, (C, lab) in enumerate(S):
            ok = np.array([n in C for n, _ in show])          # FiQA: no LLM controllers
            g = np.array([C[n]["gain"] for n, _ in show if n in C])
            lo = g - np.array([C[n]["gain_ci95"][0] for n, _ in show if n in C])
            hi = np.array([C[n]["gain_ci95"][1] for n, _ in show if n in C]) - g
            ax.errorbar(g, (y + off[j])[ok], xerr=[lo, hi], fmt=mk[j], color="black", mfc="black" if j % 2 == 0 else "white",
                        ms=4, elinewidth=0.6, capsize=1.5, label=lab)
        ax.axvline(0, color="0.4", linewidth=0.8, linestyle=(0, (4, 2)))
        ax.set_title(t, loc="left", fontsize=9, fontweight="bold")
        ax.set_xlabel(r"$\Delta$nDCG@10 vs. $a^\ast$ (95% bootstrap CI)")
        ax.spines[["top", "right"]].set_visible(False)
        ax.legend(frameon=False, fontsize=7.5, loc="upper center", bbox_to_anchor=(0.5, -0.22), ncol=len(S))
    axes[0].set_yticks(y, [l for _, l in show])
    fig.tight_layout()
    for ext in ("pdf", "eps"):
        fig.savefig(out / f"Fig7.{ext}", bbox_inches="tight")
    plt.close(fig)


def main():
    art = Path(sys.argv[1])
    (art / "generated" / "tab_test_public.tex").write_text(tab_public())
    (art / "generated" / "tab_test_clin.tex").write_text(tab_clin())
    (art / "generated" / "test_numbers.tex").write_text(numbers())
    fig(art / "figures")
    print("written: generated/tab_test_public.tex, tab_test_clin.tex, test_numbers.tex, figures/Fig7")


if __name__ == "__main__":
    main()
